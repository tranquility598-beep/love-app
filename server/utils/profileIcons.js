/**
 * Разметка иконки. Возвращает готовый <svg>, а не путь: у части иконок
 * внутри свои fill/stroke, и склеивать их в одном шаблоне снаружи было бы
 * source of surprises.
 */
function iconSvg(id, { size = 20, className = 'pf-ico' } = {}) {
  const inner = ICONS[id] || FALLBACK;
  return `<svg class="${className}" width="${size}" height="${size}" viewBox="0 0 24 24" ${STROKE} aria-hidden="true">${inner}</svg>`;
}

function hasIcon(id) {
  return Object.prototype.hasOwnProperty.call(ICONS, id);
}

